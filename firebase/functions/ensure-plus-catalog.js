/**
 * One-shot helper: inspect the live Stripe account and ensure a Famielda Plus
 * monthly price exists. Reads STRIPE_SECRET_KEY from the environment or
 * .secret.local. Never prints secret keys.
 */
const fs = require("fs");
const path = require("path");
const Stripe = require("stripe");

const PLUS_AMOUNT = 999;
const PLUS_CURRENCY = "usd";
const PLUS_INTERVAL = "month";
const PRODUCT_NAME = "Famielda Plus";

function loadSecretLocal() {
  const file = path.join(__dirname, ".secret.local");
  if (!fs.existsSync(file)) return {};
  const values = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 1) continue;
    values[trimmed.slice(0, eq)] = trimmed.slice(eq + 1).trim();
  }
  return values;
}

function secretKey() {
  const fromEnv = String(process.env.STRIPE_SECRET_KEY || "").trim();
  if (fromEnv) return fromEnv;
  return String(loadSecretLocal().STRIPE_SECRET_KEY || "").trim();
}

async function findPlusProduct(stripe) {
  const products = await stripe.products.list({ limit: 100, active: true });
  return products.data.find((item) => {
    const name = String(item.name || "").toLowerCase();
    return item.metadata?.famieldaPlan === "plus"
      || name === "famielda plus"
      || name === "plus";
  }) || null;
}

async function findPlusPrice(stripe, productId) {
  const prices = await stripe.prices.list({
    product: productId,
    active: true,
    limit: 100,
  });
  return prices.data.find((item) => (
    item.type === "recurring"
    && item.recurring?.interval === PLUS_INTERVAL
    && item.unit_amount === PLUS_AMOUNT
    && item.currency === PLUS_CURRENCY
  )) || null;
}

async function main() {
  const key = secretKey();
  if (!key || !key.startsWith("sk_")) {
    throw new Error("STRIPE_SECRET_KEY is missing from the environment or .secret.local.");
  }
  if (!key.startsWith("sk_live_")) {
    throw new Error("Expected a live Stripe secret key (sk_live_...).");
  }

  const stripe = new Stripe(key, {
    appInfo: { name: "Famielda", version: "1.0.0" },
  });

  const account = await stripe.accounts.retrieve();
  const products = await stripe.products.list({ limit: 100, active: true });
  const existingWebhooks = await stripe.webhookEndpoints.list({ limit: 20 });

  let product = await findPlusProduct(stripe);
  let createdProduct = false;
  if (!product) {
    product = await stripe.products.create({
      name: PRODUCT_NAME,
      description: "Multiple people on the care circle, medication, documents, care history, and advanced reports.",
      metadata: { famieldaPlan: "plus", source: "famielda" },
    });
    createdProduct = true;
  }

  let price = await findPlusPrice(stripe, product.id);
  let createdPrice = false;
  if (!price) {
    price = await stripe.prices.create({
      product: product.id,
      currency: PLUS_CURRENCY,
      unit_amount: PLUS_AMOUNT,
      recurring: { interval: PLUS_INTERVAL },
      nickname: "Famielda Plus monthly",
      metadata: { famieldaPlan: "plus", source: "famielda" },
    });
    createdPrice = true;
  }

  const envPath = path.join(__dirname, ".env");
  const envBody = [
    "# Generated by ensure-plus-catalog.js — price IDs are not secrets.",
    `STRIPE_PLUS_PRICE_ID=${price.id}`,
    `STRIPE_PLUS_PRODUCT_ID=${product.id}`,
    "",
  ].join("\n");
  fs.writeFileSync(envPath, envBody, "utf8");

  const summary = {
    livemode: true,
    accountId: account.id,
    chargesEnabled: Boolean(account.charges_enabled),
    payoutsEnabled: Boolean(account.payouts_enabled),
    country: account.country || "",
    productId: product.id,
    productName: product.name,
    createdProduct,
    priceId: price.id,
    amount: price.unit_amount,
    currency: price.currency,
    interval: price.recurring?.interval,
    createdPrice,
    existingProductCount: products.data.length,
    webhookUrls: existingWebhooks.data.map((item) => ({
      id: item.id,
      url: item.url,
      status: item.status,
      livemode: Boolean(item.livemode),
    })),
  };

  process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
});
